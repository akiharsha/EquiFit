# Redefine the recommend_for_input function to ensure it's in scope
def recommend_for_input(sector, skills, location, cgpa, topk=5):
    # Check if companies_df is empty, indicating a loading error
    if companies_df.empty:
        print("Warning: companies_df is empty. Recommendation logic cannot run.")
        return [{"job":"Error","company":"Data not loaded","score":0.0}]

    # Combine sector and skills into a list of keywords
    keywords = [kw.strip() for kw in sector.split(';') + skills.split(',') if kw.strip()]

    # Filter companies based on keywords in Description (case-insensitive)
    filtered_companies = companies_df[
        companies_df['Description'].str.contains('|'.join(keywords), case=False, na=False)
    ].copy() # Use .copy() to avoid SettingWithCopyWarning

    # Filter by location (case-insensitive), skip if location is empty
    if location:
        filtered_companies = filtered_companies[
            filtered_companies['City'].str.contains(location, case=False, na=False)
        ]

    # Convert Minimum_CGPA_Percentage to numeric and handle NaNs
    filtered_companies['Minimum_CGPA_Percentage_Numeric'] = pd.to_numeric(
        filtered_companies['Minimum_CGPA_Percentage'], errors='coerce'
    ).fillna(0.0)

    # Filter by CGPA
    filtered_companies = filtered_companies[
        cgpa >= filtered_companies['Minimum_CGPA_Percentage_Numeric']
    ]

    # Calculate score based on matching keywords in Description
    def calculate_score(description, keywords):
        score = 0
        if pd.isna(description): # Handle potential NaN descriptions
            return 0
        for keyword in keywords:
            if keyword.lower() in description.lower():
                score += 1
        return score

    # Apply score calculation only if filtered_companies is not empty
    if not filtered_companies.empty:
        filtered_companies['score'] = filtered_companies['Description'].apply(
            lambda x: calculate_score(x, keywords)
        )
    else:
        # If no companies match filters, return empty list
        return []


    # Sort by score and select topk
    recommended_companies = filtered_companies.sort_values(by='score', ascending=False).head(topk)

    # Format results by iterating through rows, using 'Role_Title'
    recommendations = []
    for index, row in recommended_companies.iterrows():
        recommendations.append({
            'job': row['Role_Title'],
            'company': row['Company_Name'],
            'score': row['score']
        })

    return recommendations


