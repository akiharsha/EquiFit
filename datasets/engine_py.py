@app.route('/recommend', methods=['POST'])
def recommend():
    data = request.json
    # Extract data from the incoming JSON request
    sector = data.get('Sector_Preferences', '')
    skills = data.get('Skills', '')
    location = data.get('Location_Preference', '')
    cgpa = data.get('CGPA_or_Percentage_Normalized', 0.0) # Use 0.0 as default for CGPA

    # Call the actual recommend_for_input function
    try:
        recs = recommend_for_input(sector, skills, location, cgpa, topk=5)
    except Exception as e:
        # Catch any other potential errors in the recommendation function
        print(f"Error during recommendation generation: {e}")
        recs = [{"job":"Error","company":f"Internal Server Error: {e}","score":0.0}]


    # Return the recommendations as a JSON response
    return jsonify(recs)

