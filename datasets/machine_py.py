# Load into pandas
import pandas as pd

companies_df = pd.read_csv('companies.csv')
applicants_df = pd.read_csv('preprocessed_applicants.csv')

print('Companies:', companies_df.shape)
print('Applicants:', applicants_df.shape)

# Cell 2: Build profile text for embeddings
# (Adjust the columns depending on what you actually have in your CSVs)

def build_job_text(row):
    parts = []
    if 'Role_Title' in row and pd.notna(row['Role_Title']):
        parts.append(str(row['Role_Title']))
    if 'Description' in row and pd.notna(row['Description']):
        parts.append(str(row['Description']))
    if 'Industry_Type' in row and pd.notna(row['Industry_Type']):
        parts.append(str(row['Industry_Type']))
    return ' | '.join(parts)

def build_applicant_text(row):
    parts = []
    for col in ['Skills', 'Education', 'Preferred_Sectors', 'Location', 'Profile_Summary']:
        if col in row and pd.notna(row[col]):
            parts.append(str(row[col]))
    if 'profile_text' in row and pd.notna(row['profile_text']):
        parts.append(str(row['profile_text']))
    return ' | '.join(parts)

# Create combined text columns
companies_df['job_text'] = companies_df.apply(build_job_text, axis=1)
applicants_df['app_text'] = applicants_df.apply(build_applicant_text, axis=1)

print("Sample job text:\n", companies_df['job_text'].iloc[0])
print("\nSample applicant text:\n", applicants_df['app_text'].iloc[0])

# Cell 3: Compute embeddings for jobs and applicants

from sentence_transformers import SentenceTransformer

# Load the pre-trained model (small, fast, good for semantic search)
model = SentenceTransformer('all-MiniLM-L6-v2')

# Get text lists
job_texts = companies_df['job_text'].fillna('').tolist()
app_texts = applicants_df['app_text'].fillna('').tolist()

print('Encoding job postings...')
job_emb = model.encode(job_texts, convert_to_numpy=True, show_progress_bar=True)

print('Encoding applicants...')
app_emb = model.encode(app_texts, convert_to_numpy=True, show_progress_bar=True)

print('Job embeddings shape:', job_emb.shape)
print('Applicant embeddings shape:', app_emb.shape)

# Cell 4: Compute semantic similarity between applicants and jobs

from sklearn.metrics.pairwise import cosine_similarity
import numpy as np

# Compute cosine similarity (rows = applicants, columns = jobs)
sim_matrix = cosine_similarity(app_emb, job_emb)

# Cosine similarity returns values in [-1, 1]; optional rescale to [0,1]
sim_norm = (sim_matrix + 1) / 2

print("Similarity matrix shape:", sim_norm.shape)
print("Example similarity scores (first applicant vs first 5 jobs):")
print(sim_norm[0, :5])

# Quick look at top matches for first applicant
top_jobs = np.argsort(-sim_norm[0])[:5]  # top 5 jobs
print("Top 5 job indices for applicant 0:", top_jobs)
for j in top_jobs:
    print(f"Job index {j}: {companies_df.iloc[j]['Company_Name']} - score {sim_norm[0,j]:.3f}")

# Parse skills into sets for comparison
def parse_skills(s):
    if pd.isna(s):
        return set()
    if isinstance(s, str):
        return set([x.strip().lower() for x in s.split(',') if x.strip()])
    if isinstance(s, list):
        return set([x.strip().lower() for x in s])
    return set()

app_skills = applicants_df.get('Skills', pd.Series(['']*len(applicants_df))).apply(parse_skills)
job_skills = companies_df.get('Required_Skills', pd.Series(['']*len(companies_df))).apply(parse_skills)

num_apps = len(applicants_df)
num_jobs = len(companies_df)

# Initialize skill overlap matrix
skill_matrix = np.zeros((num_apps, num_jobs))

# Compute skill overlap ratio for each applicant-job pair
for i, a_sk in enumerate(app_skills):
    for j, j_sk in enumerate(job_skills):
        if len(j_sk) == 0:
            skill_matrix[i, j] = 0.0
        else:
            skill_matrix[i, j] = len(a_sk & j_sk) / max(len(j_sk), 1)

print("Skill matrix shape:", skill_matrix.shape)
print("Example skill scores (first applicant vs first 5 jobs):")
print(skill_matrix[0, :5])

# Weights for combining semantic and skill scores
w_sem = 0.7
w_skill = 0.3

# Combine normalized semantic similarity with skill overlap
score_matrix = (w_sem * sim_norm) + (w_skill * skill_matrix)

print("Combined score matrix shape:", score_matrix.shape)
print("Example combined scores (first applicant vs first 5 jobs):")
print(score_matrix[0, :5])

# Initialize eligibility mask (1 = eligible, 0 = ineligible)
elig_mask = np.ones_like(score_matrix, dtype=int)

# Example: Education requirement check
if 'Education_Required' in companies_df.columns and 'Education' in applicants_df.columns:
    job_edu = companies_df['Education_Required'].fillna('').tolist()
    app_edu = applicants_df['Education'].fillna('').tolist()
    for i in range(num_apps):
        for j in range(num_jobs):
            req = job_edu[j].strip().lower()
            have = app_edu[i].strip().lower()
            if req and req not in have:
                elig_mask[i,j] = 0

# Apply eligibility mask
score_matrix = score_matrix * elig_mask

import pulp

I = range(num_apps)
J = range(num_jobs)

# Initialize problem
prob = pulp.LpProblem('pm_matching', pulp.LpMaximize)

# Decision variables: x[i][j] = 1 if applicant i assigned to job j
x = pulp.LpVariable.dicts('x', (I, J), cat='Binary')

# Objective: maximize total score
prob += pulp.lpSum([float(score_matrix[i, j]) * x[i][j] for i in I for j in J])

# Constraint: each applicant assigned at most once
for i in I:
    prob += pulp.lpSum([x[i][j] for j in J]) <= 1

# Constraint: respect job capacity (default 1 if missing)
capacities = companies_df.get('capacity', pd.Series([1]*num_jobs)).fillna(1).astype(int).tolist()
for j in J:
    prob += pulp.lpSum([x[i][j] for i in I]) <= capacities[j]

# Solve ILP
prob.solve(pulp.PULP_CBC_CMD(msg=True))

print("ILP status:", pulp.LpStatus[prob.status])

assignments = []
for i in I:
    for j in J:
        if x[i][j].value() is not None and x[i][j].value() > 0.5:
            assignments.append({
                'applicant_index': i,
                'applicant_id': applicants_df.iloc[i].get('Applicant_ID', i),
                'job_index': j,
                'company': companies_df.iloc[j].get('Company_Name', ''),
                'role': companies_df.iloc[j].get('Role_Title', ''),
                'score': float(score_matrix[i, j])
            })

assign_df = pd.DataFrame(assignments)
assign_df.to_csv('assignments.csv', index=False)

print("Assignments saved. Total placements:", len(assign_df))

# Top matches for first 5 applicants (optional)
for i in range(min(5, num_apps)):
    topk = np.argsort(-score_matrix[i])[:5]
    print("\nApplicant", applicants_df.iloc[i].get('Applicant_ID', i), "top matches:")
    for rank, j in enumerate(topk, start=1):
        print(f" {rank}. Job idx {j}, company {companies_df.iloc[j].get('Company_Name','')}, score {score_matrix[i,j]:.3f}")

# Plot histogram of assigned scores
if len(assign_df) > 0:
    import matplotlib.pyplot as plt
    plt.hist(assign_df['score'], bins=20)
    plt.title('Distribution of assigned scores')
    plt.xlabel('Score')
    plt.ylabel('Count')
    plt.show()